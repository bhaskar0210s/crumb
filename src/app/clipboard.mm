// Apps mark passwords and other short-lived content with these types (see nspasteboard.org) so that clipboard
// tools leave it alone.
NSSet<NSString*>* ignoredTypes() {
    static NSSet<NSString*>* types = [NSSet setWithArray:@[
        @"org.nspasteboard.ConcealedType", @"org.nspasteboard.TransientType", @"org.nspasteboard.AutoGeneratedType",
        @"com.agilebits.onepassword", @"com.typeit4me.clipping", @"de.petermaurer.TransientPasteboardType",
        @"Pasteboard generator type", @"net.antelle.keeweb"
    ]];
    return types;
}

constexpr size_t kInlineBytes = 256 * 1024;  // smaller texts are saved at once, larger ones in the background
constexpr double kThumbHeight = 80;          // pixels, 40 points on a Retina screen
constexpr double kThumbMaxWidth = 480;

NSString* const kJPEG = @"public.jpeg";

// Text that an app put next to a picture only to label it: a URL, a path or a file name.
bool isLabel(NSData* text) {
    if (text.length == 0 || text.length > 2048) return false;
    NSString* s = [[NSString alloc] initWithData:text encoding:NSUTF8StringEncoding];
    if (!s || [s rangeOfCharacterFromSet:NSCharacterSet.newlineCharacterSet].location != NSNotFound) return false;
    if ([s containsString:@"://"] || [s hasPrefix:@"/"] || [s hasPrefix:@"data:"]) return true;
    return s.pathExtension.length > 0 && [s rangeOfString:@" "].location == NSNotFound;
}

std::string head(NSData* data) {
    const std::string_view all(static_cast<const char*>(data.bytes), data.length);
    return std::string(crumb::utf8Prefix(all, crumb::Store::kHeadBytes));
}

NSData* mapped(const std::string& path) {
    return [NSData dataWithContentsOfFile:@(path.c_str()) options:NSDataReadingMappedIfSafe error:nil];
}

// The largest picture in a source (TIFFs often hold 1x and 2x versions), and whether it is stored on its side.
size_t largestImage(CGImageSourceRef source, double& width, double& height, bool& rotated) {
    size_t best = 0;
    width = height = 0;
    rotated = false;
    const size_t count = CGImageSourceGetCount(source);
    for (size_t i = 0; i < count; ++i) {
        CFDictionaryRef props = CGImageSourceCopyPropertiesAtIndex(source, i, nullptr);
        if (!props) continue;
        double w = 0, h = 0;
        if (auto n = static_cast<CFNumberRef>(CFDictionaryGetValue(props, kCGImagePropertyPixelWidth)))
            CFNumberGetValue(n, kCFNumberDoubleType, &w);
        if (auto n = static_cast<CFNumberRef>(CFDictionaryGetValue(props, kCGImagePropertyPixelHeight)))
            CFNumberGetValue(n, kCFNumberDoubleType, &h);
        int orientation = 1;
        if (auto n = static_cast<CFNumberRef>(CFDictionaryGetValue(props, kCGImagePropertyOrientation)))
            CFNumberGetValue(n, kCFNumberIntType, &orientation);
        CFRelease(props);
        if (w * h > width * height) {
            width = w;
            height = h;
            best = i;
            rotated = orientation >= 5 && orientation <= 8;
        }
    }
    return best;
}

NSData* encodePNG(CGImageRef image) {
    NSMutableData* data = [NSMutableData data];
    CGImageDestinationRef dest =
        CGImageDestinationCreateWithData((__bridge CFMutableDataRef)data, CFSTR("public.png"), 1, nullptr);
    if (!dest) return nil;
    CGImageDestinationAddImage(dest, image, nullptr);
    const bool ok = CGImageDestinationFinalize(dest);
    CFRelease(dest);
    return ok ? data : nil;
}

// `width` and `height` are the picture's size as shown (after any rotation).
void writeThumbnail(CGImageSourceRef source, size_t index, double width, double height, const std::string& path) {
    if (width < 1 || height < 1) return;
    const double scale = std::min({1.0, kThumbHeight / height, kThumbMaxWidth / width});
    const double side = std::max(1.0, std::ceil(std::max(width, height) * scale));
    NSDictionary* options = @{
        (id)kCGImageSourceCreateThumbnailFromImageAlways : @YES,
        (id)kCGImageSourceCreateThumbnailWithTransform : @YES,
        (id)kCGImageSourceThumbnailMaxPixelSize : @(side),
    };
    CGImageRef thumb = CGImageSourceCreateThumbnailAtIndex(source, index, (__bridge CFDictionaryRef)options);
    if (!thumb) return;
    if (NSData* png = encodePNG(thumb)) crumb::writeFile(path, png.bytes, png.length);
    CGImageRelease(thumb);
}

}  // namespace

// Converts a stored picture to the format a pasting app asks for, only when it asks.
// Keeps the picture mapped, so pasting still works after its entry is deleted.
@interface CRImageProvider : NSObject <NSPasteboardItemDataProvider>
@property(nonatomic, strong) NSData* data;
@end

@implementation CRImageProvider

- (void)pasteboard:(NSPasteboard*)pasteboard item:(NSPasteboardItem*)item provideDataForType:(NSPasteboardType)type {
    @autoreleasepool {
        CGImageSourceRef source = CGImageSourceCreateWithData((__bridge CFDataRef)self.data, nullptr);
        if (!source) return;
        NSMutableData* data = [NSMutableData data];
        CFStringRef uti = [type isEqualToString:NSPasteboardTypeTIFF] ? CFSTR("public.tiff") : CFSTR("public.png");
        if (CGImageDestinationRef dest = CGImageDestinationCreateWithData((__bridge CFMutableDataRef)data, uti, 1, nullptr)) {
            CGImageDestinationAddImageFromSource(dest, source, 0, nullptr);
            if (CGImageDestinationFinalize(dest)) [item setData:data forType:type];
            CFRelease(dest);
        }
        CFRelease(source);
    }
}

@end

@implementation CRClipboard {
    crumb::Store* _store;
    dispatch_source_t _timer;
    dispatch_queue_t _io;
    NSInteger _seen;     // change count already handled
    NSInteger _own;      // change count of Crumb's own last write
    NSInteger _noticed;  // a change count waiting for its app to finish writing
    CFTimeInterval _noticedAt;
    NSInteger _saving;   // saves still running in the background
    NSUInteger _picks;   // entries put back on the pasteboard so far
    NSUInteger _clears;  // times the history was cleared
}

- (instancetype)initWithStore:(crumb::Store*)store {
    if ((self = [super init])) {
        _store = store;
        _seen = -1;
        _own = -1;
        _noticed = -1;
        _io = dispatch_queue_create("crumb.save",
                                    dispatch_queue_attr_make_with_qos_class(DISPATCH_QUEUE_SERIAL, QOS_CLASS_UTILITY, 0));
    }
    return self;
}

- (void)start {
    // Apps don't announce copies, so the change count is checked twice a second (a cheap call).
    _timer = dispatch_source_create(DISPATCH_SOURCE_TYPE_TIMER, 0, 0, dispatch_get_main_queue());
    dispatch_source_set_timer(_timer, dispatch_time(DISPATCH_TIME_NOW, 0), NSEC_PER_SEC / 2, NSEC_PER_SEC / 10);
    __weak CRClipboard* weakSelf = self;
    dispatch_source_set_event_handler(_timer, ^{
        [weakSelf poll];
    });
    dispatch_resume(_timer);
}

- (void)poll {
    [self pollWaiting:YES];
}

- (void)pollNow {
    [self pollWaiting:NO];
}

// Apps copy in two steps, clearing the pasteboard and then writing to it, so a change is read once it has
// settled for a moment, and looked at again for a while if it still reads empty.
- (void)pollWaiting:(BOOL)settle {
    @autoreleasepool {
        NSPasteboard* pasteboard = NSPasteboard.generalPasteboard;
        const NSInteger count = pasteboard.changeCount;
        if (count == _seen) return;
        const CFTimeInterval now = CACurrentMediaTime();
        if (count != _noticed) {
            _noticed = count;
            _noticedAt = now;
            if (settle) {
                __weak CRClipboard* weakSelf = self;
                dispatch_after(dispatch_time(DISPATCH_TIME_NOW, NSEC_PER_SEC / 10), dispatch_get_main_queue(), ^{
                    [weakSelf poll];
                });
                return;
            }
        }
        if (settle && now - _noticedAt < 0.09) return;
        if (count != _own && ![self capture:pasteboard] && now - _noticedAt < 2) return;
        _seen = count;
    }
}

- (void)changed {
    if (self.onChange) self.onChange();
}

// Saves what was copied. Returns NO when the pasteboard holds nothing readable (yet).
- (BOOL)capture:(NSPasteboard*)pasteboard {
    NSArray<NSPasteboardItem*>* items = pasteboard.pasteboardItems;
    if (items.count == 0) return NO;
    NSSet<NSString*>* ignored = ignoredTypes();
    for (NSPasteboardItem* item in items)
        for (NSPasteboardType type in item.types)
            if ([ignored containsObject:type]) return YES;

    // Files arrive as one file URL per pasteboard item.
    NSMutableArray<NSString*>* paths = [NSMutableArray array];
    for (NSPasteboardItem* item in items) {
        NSString* string = [item stringForType:NSPasteboardTypeFileURL];
        NSURL* url = string ? [NSURL URLWithString:string] : nil;
        if (url.isFileURL && url.path.length) [paths addObject:url.path];
    }
    if (paths.count) {
        [self saveFiles:paths];
        return YES;
    }

    NSPasteboardItem* first = items.firstObject;
    NSData* text = [first dataForType:NSPasteboardTypeString];
    NSData* rtf = [first dataForType:NSPasteboardTypeRTF];
    NSData* html = [first dataForType:NSPasteboardTypeHTML];
    if (text.length == 0) text = [[pasteboard stringForType:NSPasteboardTypeString] dataUsingEncoding:NSUTF8StringEncoding];
    if (text.length == 0 && rtf.length) {
        NSAttributedString* styled = [[NSAttributedString alloc] initWithRTF:rtf documentAttributes:nil];
        text = [styled.string dataUsingEncoding:NSUTF8StringEncoding];
    }

    NSString* imageType = nil;
    NSData* image = nil;
    for (NSPasteboardType type in @[ NSPasteboardTypePNG, kJPEG, NSPasteboardTypeTIFF ]) {
        if ([first.types containsObject:type] && (image = [first dataForType:type]).length) {
            imageType = type;
            break;
        }
    }

    if (image && (text.length == 0 || (rtf.length == 0 && isLabel(text))))
        [self saveImage:image type:imageType label:text];
    else if (text.length)
        [self saveText:text rtf:rtf html:html];
    else
        return first.types.count > 0;  // something Crumb doesn't keep (or not written yet)
    return YES;
}

// Copying something Crumb already has just moves that entry to the top. Returns NO for new content.
- (BOOL)promote:(crumb::Kind)kind fingerprint:(uint64_t)fingerprint {
    const auto& items = _store->items();
    for (size_t i = 0; i < items.size(); ++i) {
        if (items[i].kind != kind || items[i].fingerprint != fingerprint) continue;
        if (i > 0) {
            _store->moveToTop(i);
            [self changed];
        }
        return YES;
    }
    return NO;
}

// Saves an entry in the background. Saves run in order, so the history keeps the order of the copies even
// when a big one takes a while.
- (void)saveInBackground:(crumb::Kind)kind data:(NSData*)data write:(crumb::Item (^)(uint64_t entry, uint64_t fingerprint))write {
    crumb::Store* store = _store;
    __weak CRClipboard* weakSelf = self;
    const NSUInteger picks = _picks, clears = _clears;
    ++_saving;
    dispatch_async(_io, ^{
        const uint64_t fingerprint = crumb::fingerprint(data.bytes, data.length);
        __block uint64_t entry = 0;
        dispatch_sync(dispatch_get_main_queue(), ^{
            CRClipboard* clipboard = weakSelf;
            if (clipboard && ![clipboard promote:kind fingerprint:fingerprint]) entry = store->newId();
        });
        crumb::Item item;
        if (entry) {
            @autoreleasepool {
                item = write(entry, fingerprint);
            }
        }
        dispatch_async(dispatch_get_main_queue(), ^{
            CRClipboard* clipboard = weakSelf;
            if (!clipboard) return;
            --clipboard->_saving;
            if (!item.id) return;
            if (clipboard->_clears != clears) {  // the history was cleared meanwhile
                store->forget(item.id);
                return;
            }
            // An entry picked from the list since this copy is newer, so it stays on top.
            store->add(item, clipboard->_picks != picks ? 1 : 0);
            [clipboard changed];
        });
    });
}

- (void)saveText:(NSData*)text rtf:(NSData*)rtf html:(NSData*)html {
    crumb::Store* store = _store;
    crumb::Item (^write)(uint64_t, uint64_t) = ^crumb::Item(uint64_t entry, uint64_t fingerprint) {
        crumb::Item item;
        item.id = entry;
        item.kind = crumb::Kind::Text;
        item.flags = crumb::kHasText;
        item.bytes = text.length;
        item.fingerprint = fingerprint;
        item.head = head(text);
        if (!crumb::writeFile(store->file(entry, "txt"), text.bytes, text.length)) item.id = 0;
        if (rtf.length && crumb::writeFile(store->file(entry, "rtf"), rtf.bytes, rtf.length)) item.flags |= crumb::kHasRTF;
        if (html.length && crumb::writeFile(store->file(entry, "html"), html.bytes, html.length))
            item.flags |= crumb::kHasHTML;
        return item;
    };
    if (_saving || text.length + rtf.length + html.length > kInlineBytes) {
        [self saveInBackground:crumb::Kind::Text data:text write:write];
        return;
    }
    // Small texts are saved at once, so they are already in the list if it opens right after the copy.
    const uint64_t fingerprint = crumb::fingerprint(text.bytes, text.length);
    if ([self promote:crumb::Kind::Text fingerprint:fingerprint]) return;
    crumb::Item item = write(store->newId(), fingerprint);
    if (!item.id) return;
    store->add(std::move(item));
    [self changed];
}

- (void)saveImage:(NSData*)image type:(NSString*)type label:(NSData*)label {
    crumb::Store* store = _store;
    [self saveInBackground:crumb::Kind::Image
                      data:image
                     write:^crumb::Item(uint64_t entry, uint64_t fingerprint) {
                         crumb::Item item;
                         NSDictionary* options = @{(id)kCGImageSourceShouldCache : @NO};
                         CGImageSourceRef source =
                             CGImageSourceCreateWithData((__bridge CFDataRef)image, (__bridge CFDictionaryRef)options);
                         if (!source) return item;
                         double width = 0, height = 0;
                         bool rotated = false;
                         const size_t index = largestImage(source, width, height, rotated);
                         NSData* stored = image;
                         bool jpeg = [type isEqualToString:kJPEG];
                         if ([type isEqualToString:NSPasteboardTypeTIFF] || index != 0) {
                             // TIFF is usually uncompressed; PNG keeps the same pixels in a fraction of the space.
                             // Drawn upright, as PNG has no orientation tag.
                             NSDictionary* upright = @{
                                 (id)kCGImageSourceCreateThumbnailFromImageAlways : @YES,
                                 (id)kCGImageSourceCreateThumbnailWithTransform : @YES,
                                 (id)kCGImageSourceThumbnailMaxPixelSize : @(std::max(width, height)),
                             };
                             CGImageRef decoded = CGImageSourceCreateThumbnailAtIndex(source, index, (__bridge CFDictionaryRef)upright);
                             stored = decoded ? encodePNG(decoded) : nil;
                             jpeg = false;
                             CGImageRelease(decoded);
                         }
                         if (rotated) std::swap(width, height);  // the size as the picture is shown
                         if (stored && width >= 1 && height >= 1) {
                             item.id = entry;
                             item.kind = crumb::Kind::Image;
                             item.flags = crumb::kHasImage | (jpeg ? crumb::kImageIsJPEG : 0);
                             item.bytes = image.length;
                             item.fingerprint = fingerprint;
                             item.width = static_cast<uint32_t>(width);
                             item.height = static_cast<uint32_t>(height);
                             if (!crumb::writeFile(store->imageFile(item), stored.bytes, stored.length)) item.id = 0;
                             writeThumbnail(source, index, width, height, store->file(entry, "thumb.png"));
                             if (item.id && label.length &&
                                 crumb::writeFile(store->file(entry, "txt"), label.bytes, label.length)) {
                                 item.flags |= crumb::kHasText;
                                 item.head = head(label);
                             }
                         }
                         CFRelease(source);
                         return item;
                     }];
}

- (void)saveFiles:(NSArray<NSString*>*)paths {
    NSData* list = [[paths componentsJoinedByString:@"\n"] dataUsingEncoding:NSUTF8StringEncoding];
    crumb::Store* store = _store;
    crumb::Item (^write)(uint64_t, uint64_t) = ^crumb::Item(uint64_t entry, uint64_t fingerprint) {
        crumb::Item item;
        item.id = entry;
        item.kind = crumb::Kind::Files;
        item.bytes = list.length;
        item.fingerprint = fingerprint;
        item.head = head(list);
        if (!crumb::writeFile(store->file(entry, "files"), list.bytes, list.length)) item.id = 0;
        return item;
    };
    if (_saving) {
        [self saveInBackground:crumb::Kind::Files data:list write:write];
        return;
    }
    const uint64_t fingerprint = crumb::fingerprint(list.bytes, list.length);
    if ([self promote:crumb::Kind::Files fingerprint:fingerprint]) return;
    crumb::Item item = write(store->newId(), fingerprint);
    if (!item.id) return;
    store->add(std::move(item));
    [self changed];
}

- (BOOL)busy {
    return _saving > 0;
}

- (void)clearHistory {
    ++_clears;
    _store->clear();
    [self changed];
}

- (BOOL)copyItemAtIndex:(size_t)index {
    const auto& items = _store->items();
    if (index >= items.size()) return NO;
    const crumb::Item item = items[index];
    NSPasteboard* pasteboard = NSPasteboard.generalPasteboard;
    BOOL ok = NO;
    if (item.kind == crumb::Kind::Files) {
        NSString* list = [NSString stringWithContentsOfFile:@(_store->file(item.id, "files").c_str())
                                                   encoding:NSUTF8StringEncoding
                                                      error:nil];
        NSMutableArray<NSURL*>* urls = [NSMutableArray array];
        for (NSString* path in [list componentsSeparatedByString:@"\n"])
            if (path.length) [urls addObject:[NSURL fileURLWithPath:path]];
        if (urls.count) {
            [pasteboard clearContents];
            ok = [pasteboard writeObjects:urls];
        }
    } else {
        NSPasteboardItem* entry = [NSPasteboardItem new];
        BOOL any = NO;
        if (item.flags & crumb::kHasText) {
            if (NSData* data = mapped(_store->file(item.id, "txt"))) any = [entry setData:data forType:NSPasteboardTypeString];
        }
        if (item.flags & crumb::kHasRTF) {
            if (NSData* data = mapped(_store->file(item.id, "rtf"))) [entry setData:data forType:NSPasteboardTypeRTF];
        }
        if (item.flags & crumb::kHasHTML) {
            if (NSData* data = mapped(_store->file(item.id, "html"))) [entry setData:data forType:NSPasteboardTypeHTML];
        }
        if (item.flags & crumb::kHasImage) {
            const std::string path = _store->imageFile(item);
            if (NSData* data = mapped(path)) {
                const BOOL jpeg = (item.flags & crumb::kImageIsJPEG) != 0;
                any = [entry setData:data forType:jpeg ? kJPEG : NSPasteboardTypePNG] || any;
                CRImageProvider* provider = [CRImageProvider new];
                provider.data = data;
                [entry setDataProvider:provider
                              forTypes:jpeg ? @[ NSPasteboardTypePNG, NSPasteboardTypeTIFF ] : @[ NSPasteboardTypeTIFF ]];
            }
        }
        if (any) {
            [pasteboard clearContents];
            ok = [pasteboard writeObjects:@[ entry ]];
        }
    }
    if (!ok) {
        // Its files are gone (or unreadable): drop the entry rather than offer it again.
        _store->remove(index);
        [self changed];
        return NO;
    }
    _own = _seen = pasteboard.changeCount;
    ++_picks;
    _store->moveToTop(index);
    return YES;
}

